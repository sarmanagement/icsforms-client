package org.sarmanagement.icsforms.model;

public class CommunicationEntry {
    private String nameOrFunction;
    private String primaryContact;

    public String getNameOrFunction() { return nameOrFunction; }
    public void setNameOrFunction(String nameOrFunction) { this.nameOrFunction = nameOrFunction; }
    public String getPrimaryContact() { return primaryContact; }
    public void setPrimaryContact(String primaryContact) { this.primaryContact = primaryContact; }
}
